function escapeHtml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function applyChatEdit(
  html: string,
  instruction: string,
  name: string,
): string {
  const lower = instruction.toLowerCase();
  let next = html;
  if (/calm|softer|quiet|minimal/.test(lower)) {
    next = next.replace(/#2dd4bf/g, "#7dd3fc").replace(/#12352f/g, "#0c4a6e");
  }
  if (/darker|denser|compact/.test(lower)) {
    next = next.replace("padding:22px", "padding:14px");
  }
  if (/title|rename|call it|named/.test(lower)) {
    const match = instruction.match(/(?:title|rename|call it|named)\s+[\"']?([^\"'\n.]+)[\"']?/i);
    if (match?.[1]) {
      const newName = match[1].trim();
      next = next.replace(new RegExp(escapeRegExp(name), "g"), escapeHtml(newName));
    }
  }
  if (/citation|source/.test(lower) && !next.includes("Citations panel")) {
    next = next.replace(
      "</main>",
      `<section class="panel"><h3 style="margin:0 0 4px;font-size:14px;">Citations panel</h3><p>Sources will appear here after each run.</p></section></main>`,
    );
  }
  if (/button|cta|add a/.test(lower) && !next.includes("Secondary action")) {
    next = next.replace(
      '<button class="ghost" id="clear">Clear</button>',
      '<button class="ghost" id="clear">Clear</button><button class="ghost" id="secondary">Secondary action</button>',
    );
  }
  return next;
}

function escapeRegExp(s: string) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}


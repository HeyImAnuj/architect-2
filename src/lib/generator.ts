function slugify(text: string) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 48);
}

function titleFromPrompt(prompt: string) {
  const cleaned = prompt.trim().replace(/^(build|create|make)\s+/i, "");
  const words = cleaned.split(/\s+/).slice(0, 5).join(" ");
  if (!words) return "Untitled App";
  return words.replace(/\b\w/g, (c) => c.toUpperCase());
}

function detectTemplate(prompt: string) {
  const p = prompt.toLowerCase();
  if (/sdr|sales|outreach|lead/.test(p)) return "sdr";
  if (/support|ticket|triage|helpdesk/.test(p)) return "support";
  if (/policy|legal|compliance|pdf|document/.test(p)) return "policy";
  if (/research|brief|report|analyst/.test(p)) return "research";
  if (/hr|resume|recruit|hiring/.test(p)) return "hr";
  return "generic";
}

export function buildAgents(seed: string, prompt: string): {
  agents: AgentNode[];
  edges: AgentEdge[];
} {
  const template = detectTemplate(prompt);
  const specs: Array<Omit<AgentNode, "id" | "x" | "y" | "status">> = [
    {
      name: "Router",
      role: "Classifies intent and routes work to specialists",
      model: "gpt-4.1",
      tools: ["classify", "memory"],
    },
    {
      name: template === "sdr" ? "Account Researcher" : "Researcher",
      role:
        template === "policy"
          ? "Retrieves and cites grounded document chunks"
          : "Gathers context from knowledge, tools, and the web",
      model: "claude-sonnet",
      tools: template === "policy" ? ["rag", "citations"] : ["rag", "web", "sql"],
    },
    {
      name: template === "support" ? "Triage Analyst" : "Analyst",
      role:
        template === "support"
          ? "Scores urgency and chooses a resolution path"
          : "Synthesizes findings into decisions and scores",
      model: "gpt-4.1",
      tools: ["rules", "scoring"],
    },
    {
      name: "Presenter",
      role: "Formats outputs into the product UI",
      model: "gemini-2.0",
      tools: ["markdown", "templates"],
    },
  ];

  const positions = [
    { x: 16, y: 42 },
    { x: 46, y: 20 },
    { x: 46, y: 64 },
    { x: 78, y: 42 },
  ];

  const agents: AgentNode[] = specs.map((spec, i) => ({
    id: `${seed}_a${i}`,
    ...spec,
    status: "ready",
    ...positions[i],
  }));

  const edges: AgentEdge[] = [
    { id: `${seed}_e1`, from: agents[0].id, to: agents[1].id, label: "needs facts" },
    { id: `${seed}_e2`, from: agents[0].id, to: agents[2].id, label: "needs judgment" },
    { id: `${seed}_e3`, from: agents[1].id, to: agents[3].id, label: "evidence" },
    { id: `${seed}_e4`, from: agents[2].id, to: agents[3].id, label: "decision" },
  ];

  return { agents, edges };
}

export function buildFiles(
  name: string,
  prompt: string,
  framework: FrameworkId,
  agents: AgentNode[],
): CodeFile[] {
  const slug = slugify(name) || "app";
  return [
    {
      path: "README.md",
      language: "markdown",
      content: `# ${name}\n\n${prompt}\n\nFramework: **${framework}**\n\nGenerated by Architect 2.0.\n`,
    },
    {
      path: "app/page.tsx",
      language: "tsx",
      content: `export default function Page() {\n  return (\n    <main className="min-h-screen bg-slate-950 text-slate-50 p-8">\n      <h1 className="text-3xl font-semibold">${name}</h1>\n      <p className="mt-2 text-slate-400">${prompt.replace(/`/g, "'").slice(0, 180)}</p>\n    </main>\n  );\n}\n`,
    },
    {
      path: "agents/graph.ts",
      language: "typescript",
      content: `export const graph = {\n  framework: "${framework}",\n  nodes: ${JSON.stringify(
        agents.map((a) => a.name),
        null,
        2,
      )},\n};\n`,
    },
    {
      path: "agents/router.py",
      language: "python",
      content: `class Router:\n    def run(self, message: str) -> dict:\n        return {"route": "research" if "why" in message.lower() else "analyze", "message": message}\n`,
    },
    {
      path: "package.json",
      language: "json",
      content: `{\n  "name": "${slug}",\n  "private": true,\n  "scripts": {\n    "dev": "next dev",\n    "build": "next build",\n    "start": "next start"\n  }\n}\n`,
    },
  ];
}


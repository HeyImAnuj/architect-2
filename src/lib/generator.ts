export type GenerationResult = {
  name: string;
  description: string;
  phase: BuildPhase;
  agents: AgentNode[];
  edges: AgentEdge[];
  files: CodeFile[];
  previewHtml: string;
  traces: TraceEvent[];
  messages: ChatMessage[];
};

export function generateProjectFromPrompt(input: {
  prompt: string;
  framework: FrameworkId;
  seed: string;
  knowledge?: KnowledgeFile[];
}): GenerationResult {
  const name = titleFromPrompt(input.prompt);
  const { agents, edges } = buildAgents(input.seed, input.prompt);
  const files = buildFiles(name, input.prompt, input.framework, agents);
  const previewHtml = buildPreviewHtml({
    name,
    prompt: input.prompt,
    agents,
    knowledge: input.knowledge,
  });
  const traces = buildTraces(agents);
  const now = Date.now();
  return {
    name,
    description: input.prompt.slice(0, 160),
    phase: "ready",
    agents,
    edges,
    files,
    previewHtml,
    traces,
    messages: [
      {
        id: `msg_${now}_u`,
        role: "user",
        content: input.prompt,
        timestamp: now - 1000,
      },
      {
        id: `msg_${now}_a`,
        role: "architect",
        content: `Built “${name}” with a ${agents.length}-agent graph on ${input.framework}. Preview is interactive — run a workflow inside the live app.`,
        timestamp: now,
        meta: "Plan → Agents → UI → QA",
      },
    ],
  };
}

export async function maybeEnhanceWithOpenAI(prompt: string, draftHtml: string) {
  const key = process.env.OPENAI_API_KEY;
  if (!key) return draftHtml;
  try {
    const res = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${key}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "gpt-4o-mini",
        temperature: 0.4,
        messages: [
          {
            role: "system",
            content:
              "You improve HTML for an agentic app preview. Return ONLY a full HTML document. Keep it self-contained with inline CSS/JS. No markdown.",
          },
          {
            role: "user",
            content: `App prompt:\n${prompt}\n\nCurrent HTML:\n${draftHtml.slice(0, 12000)}\n\nImprove visual polish and keep the Run agents interaction.`,
          },
        ],
      }),
    });
    if (!res.ok) return draftHtml;
    const data = await res.json();
    const content = data.choices?.[0]?.message?.content?.trim();
    if (content?.includes("<html")) return content.replace(/^```html\n?|\n?```$/g, "");
    return draftHtml;
  } catch {
    return draftHtml;
  }
}
